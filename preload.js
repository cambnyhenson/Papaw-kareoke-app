const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  libGet: () => ipcRenderer.invoke('lib-get'),
  libStatus: () => ipcRenderer.invoke('lib-status'),
  libAdd: dir => ipcRenderer.invoke('lib-add', dir),
  libRemove: id => ipcRenderer.invoke('lib-remove', id),
  libScan: id => ipcRenderer.invoke('lib-scan', id),
  onScanProgress: cb => ipcRenderer.on('scan-progress', (_e, name, n) => cb(name, n)),
  plGet: () => ipcRenderer.invoke('pl-get'),
  plSave: data => ipcRenderer.invoke('pl-save', data),
  sppFound: () => ipcRenderer.invoke('spp-found'),
  sppImport: () => ipcRenderer.invoke('spp-import'),
  sppNames: () => ipcRenderer.invoke('spp-names'),
  read: key => ipcRenderer.invoke('read', key),     // -> Uint8Array
  hasTV: () => ipcRenderer.invoke('has-tv'),
  version: () => ipcRenderer.invoke('version'),
  onUpdateReady: cb => ipcRenderer.on('update-ready', (_e, v) => cb(v)),
  installUpdate: () => ipcRenderer.invoke('update-install'),
  log: (level, msg) => ipcRenderer.invoke('log', level, msg),
  sendReport: opts => ipcRenderer.invoke('report-send', opts),
  reportConfigured: () => ipcRenderer.invoke('report-configured'),
  openLogs: () => ipcRenderer.invoke('open-logs'),
  recSave: (title, bytes, project) => ipcRenderer.invoke('rec-save', title, bytes, project),
  recList: project => ipcRenderer.invoke('rec-list', project),
  recProjects: () => ipcRenderer.invoke('rec-projects'),
  recRead: (project, name) => ipcRenderer.invoke('rec-read', project, name),
  recDelete: (project, name) => ipcRenderer.invoke('rec-delete', project, name),
  recShow: (project, name) => ipcRenderer.invoke('rec-show', project, name),
  recFolder: project => ipcRenderer.invoke('rec-folder', project),
  recRename: (project, name, title) => ipcRenderer.invoke('rec-rename', project, name, title),
  recMove: (project, name, to) => ipcRenderer.invoke('rec-move', project, name, to),
  recReorder: (project, order) => ipcRenderer.invoke('rec-reorder', project, order),
  projCreate: name => ipcRenderer.invoke('proj-create', name),
  projRename: (from, to) => ipcRenderer.invoke('proj-rename', from, to),
  projDelete: name => ipcRenderer.invoke('proj-delete', name),
  burnCheck: () => ipcRenderer.invoke('burn-check'),
  burnPrepare: () => ipcRenderer.invoke('burn-prepare'),
  burnWrite: (dir, i, bytes) => ipcRenderer.invoke('burn-write', dir, i, bytes),
  burnCleanup: dir => ipcRenderer.invoke('burn-cleanup', dir),
  burnStart: (dir, project) => ipcRenderer.invoke('burn-start', dir, project),
  onBurnEvent: cb => ipcRenderer.on('burn-event', (_e, ev) => cb(ev)),
  onAppClosing: cb => ipcRenderer.on('app-closing', () => cb()),
  closeReady: () => ipcRenderer.invoke('close-ready'),
  tvFullscreen: () => ipcRenderer.invoke('tv-fullscreen'),
  onTvChanged: cb => ipcRenderer.on('tv-changed', (_e, connected) => cb(connected)),
  keepAwake: on => ipcRenderer.invoke('keep-awake', on),
  onOpenGuide: cb => ipcRenderer.on('open-guide', () => cb()),
});
